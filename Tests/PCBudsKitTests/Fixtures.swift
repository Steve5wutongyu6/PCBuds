import Foundation

/// Captured frames from the live earbuds and from upstream-verified implementations.
///
/// They live in source rather than in a resource bundle: the tests then run identically
/// under `swift test`, under Xcode and on CI, with no resource-path guessing.
///
/// Each frame is written as `# name\n hex bytes` so a failing expectation shows the
/// original traffic.
enum Fixture {
    static let all: [String: [UInt8]] = [
        // Air5 Pro noise reports, topic 0x03 entry 0x01, two-byte little-endian value.
        "report-air5-smart": [0xAA, 0x0C, 0x00, 0x00, 0x04, 0x02, 0x60, 0x05, 0x00, 0x03, 0x01, 0x01, 0x80, 0x00],
        "report-air5-transparent": [0xAA, 0x0C, 0x00, 0x00, 0x04, 0x02, 0x67, 0x05, 0x00, 0x03, 0x01, 0x01, 0x00, 0x01],
        "report-air5-off": [0xAA, 0x0C, 0x00, 0x00, 0x04, 0x02, 0x67, 0x05, 0x00, 0x03, 0x01, 0x01, 0x08, 0x00],
        // T500 Pro noise report, one-byte value.
        "report-t500-off": [0xAA, 0x0B, 0x00, 0x00, 0x04, 0x02, 0x9B, 0x04, 0x00, 0x03, 0x01, 0x01, 0x01],
        // Battery report (topic 0x01), which the noise parser must ignore.
        "report-battery": [0xAA, 0x0F, 0x00, 0x00, 0x04, 0x02, 0x0C, 0x08, 0x00, 0x01, 0x03, 0x01, 0x64, 0x02, 0x64, 0x03, 0x50],
        // Live read-back reply 0x0C 0x81 for "off" (`00 01 01 08 00`).
        "read-reply-air5-off": [0xAA, 0x0C, 0x00, 0x00, 0x0C, 0x81, 0xF0, 0x05, 0x00, 0x00, 0x01, 0x01, 0x08, 0x00],
        // SET ACK 0x04 0x84, status 0, payload `[00]` (`len` = 7 + 1).
        "set-ack-air5": [0xAA, 0x08, 0x00, 0x00, 0x04, 0x84, 0xF0, 0x01, 0x00, 0x00],
    ]

    /// A captured frame, or an empty array if the name is not known.
    static func bytes(_ name: String) -> [UInt8] {
        all[name] ?? []
    }

    /// Hex form of a captured frame, for test names and failure output.
    static func hex(_ name: String) -> String {
        bytes(name).map { String(format: "%02x", $0) }.joined(separator: " ")
    }
}
